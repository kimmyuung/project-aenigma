/**
 * 에러 코드에 해당하는 사용자 메시지 반환
 * @param code 에러 코드 (예: 'A001', 'R002')
 * @param fallbackMessage 매핑이 없을 경우 사용할 기본 메시지
 */
export function getErrorMessage(code: string, fallbackMessage?: string): string {
    return ERROR_MESSAGES[code] || fallbackMessage || '오류가 발생했습니다. 잠시 후 다시 시도해주세요.';
}

/**
 * HTTP 상태 코드에 따른 기본 메시지 반환
 * @param status HTTP 상태 코드
 */
export function getStatusMessage(status: number): string {
    if (status >= 500) {
        return '서버에 문제가 발생했습니다. 잠시 후 다시 시도해주세요.';
    }
    if (status === 401) {
        return '로그인이 필요합니다.';
    }
    if (status === 403) {
        return '접근 권한이 없습니다.';
    }
    if (status === 404) {
        return '요청하신 정보를 찾을 수 없습니다.';
    }
    if (status === 409) {
        return '이미 처리된 요청입니다.';
    }
    if (status >= 400) {
        return '요청을 처리할 수 없습니다.';
    }
    return '오류가 발생했습니다.';
}

/**
 * Validation 에러 메시지 포맷팅
 * @param errors 필드 에러 배열
 */
export function formatValidationErrors(errors: ApiErrorResponse['errors']): string {
    if (!errors || errors.length === 0) {
        return '입력 내용을 확인해주세요.';
    }

    if (errors.length === 1) {
        return errors[0].reason;
    }

    return errors.map(e => `• ${e.reason}`).join('\n');
}
